#!/usr/bin/env python3
"""
Tables of yesmath (src/ym_tables.c), computed on the host because the kernel
has no floating point. Each is a list of segments (value at the start, rise
over the segment), the start moved by half the chord's largest deviation so
the interpolation error is split between both sides.
  ym_log_seg  log2(1 + f),  f in [0, 1), 1024 segments, Q32
  ym_exp_seg  2^f,          f in [0, 1), 1024 segments, Q31
  ym_sin_seg  sin(2 pi t),  t in [0, 1), 1024 segments, Q30
  ym_atan_seg atan(t),      t in [0, 1], 1024 segments, Q32
and the resampler's windowed sinc, 256 phases x 8 taps, Q15 (Blackman,
cut-off 0.45 of the input rate, each phase summing to 1).
Usage: python3 math/gen_tables.py > math/ym_tables.c
"""
import math

import numpy as np


def q(v, bits):
    return int(round(v * 2 ** bits))


def centred(fn, lo, hi, n, bits):
    out = []
    for i in range(n):
        x0, x1 = lo + (hi - lo) * i / n, lo + (hi - lo) * (i + 1) / n
        a, b = fn(x0), fn(x1)
        dev = [fn(x0 + (x1 - x0) * t / 64) - (a + (b - a) * t / 64) for t in range(65)]
        out.append((q(a + (max(dev) + min(dev)) / 2, bits), q(b, bits) - q(a, bits)))
    return out


def segs(name, ctype, pairs):
    rows = [", ".join(f"{{ {a}, {b} }}" for a, b in pairs[i:i + 4]) for i in range(0, len(pairs), 4)]
    return f"const {ctype} {name}[{len(pairs)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def sinc_table(phases=256, taps=8):
    rows = []
    for p in range(phases):
        k = np.arange(taps) - 3 - p / phases
        h = 0.9 * np.sinc(0.9 * k) * (0.42 + 0.5 * np.cos(np.pi * k / 4.5) + 0.08 * np.cos(2 * np.pi * k / 4.5))
        rows.append(np.round(h / h.sum() * 32768).astype(int))
    return rows


def main():
    print("// Generated by math/gen_tables.py: do not edit.")
    print('#include "ym_internal.h"\n')
    print(segs("ym_log_seg", "YmSegU", centred(lambda f: math.log2(1 + f), 0, 1, 1024, 32)))
    print(segs("ym_exp_seg", "YmSegU", centred(lambda f: 2 ** f, 0, 1, 1024, 31)))
    print(segs("ym_sin_seg", "YmSegI", centred(lambda t: math.sin(2 * math.pi * t), 0, 1, 1024, 30)))
    print(segs("ym_atan_seg", "YmSegU", centred(math.atan, 0, 1, 1024, 32)))
    rows = sinc_table()
    print("const ym_i16 ym_sinc8[256][8] = {\n    " + ",\n    ".join(
        "{ " + ", ".join(str(v) for v in r) + " }" for r in rows) + "\n};")


if __name__ == "__main__":
    main()
