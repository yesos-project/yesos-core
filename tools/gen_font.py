#!/usr/bin/env python3
"""
Generates graphics/font_data.c from fonts/yesos-8x16.txt and checks the font:
well-formed glyphs, every printable ASCII character and the Spanish set
present, and the metrics the drawing code relies on (capitals and digits on
rows 2-10, x-height 4-10, descenders reaching row 12 or 13, rows 14-15
empty). Exits non-zero on any problem.

Usage: python3 tools/gen_font.py > graphics/font_data.c
       python3 tools/gen_font.py --check
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(os.path.dirname(HERE), "fonts", "yesos-8x16.txt")
REQUIRED = [chr(c) for c in range(0x20, 0x7F)] + list("áéíóúÁÉÍÓÚñÑüÜ¿¡°«»")


def load(path=FONT):
    glyphs, lines = {}, open(path, encoding="utf-8").read().split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.startswith("U+"):
            i += 1
            continue
        cp = int(line.split()[0][2:], 16)
        rows = lines[i + 1:i + 17]
        if cp > 0xFF:
            raise SystemExit(f"U+{cp:04X}: only code points up to U+00FF fit the table")
        if cp in glyphs:
            raise SystemExit(f"U+{cp:04X} defined twice")
        if len(rows) != 16 or any(len(r) != 8 or set(r) - set("#.") for r in rows):
            raise SystemExit(f"U+{cp:04X}: needs 16 rows of 8 characters '#' or '.'")
        glyphs[cp] = [sum(1 << (7 - k) for k, ch in enumerate(r) if ch == "#") for r in rows]
        i += 17
    return glyphs


def ink_rows(g):
    return [r for r in range(16) if g[r]]


def check(glyphs):
    errors = []
    for ch in REQUIRED:
        if ord(ch) not in glyphs:
            errors.append(f"missing {ch!r}")
    for cp, g in glyphs.items():
        if g[14] or g[15]:
            errors.append(f"U+{cp:04X}: ink in rows 14-15 (reserved for line spacing)")
    for ch in "ABCDEFGHIJKLMNOPRSTUVWXYZ0123456789":
        rows = ink_rows(glyphs[ord(ch)])
        if (rows[0], rows[-1]) != (2, 10):
            errors.append(f"{ch!r}: rows {rows[0]}-{rows[-1]}, capitals and digits use 2-10")
    for ch in "acemnorsuvwxz":
        rows = ink_rows(glyphs[ord(ch)])
        if (rows[0], rows[-1]) != (4, 10):
            errors.append(f"{ch!r}: rows {rows[0]}-{rows[-1]}, x-height letters use 4-10")
    for ch in "gjpqy":
        rows = ink_rows(glyphs[ord(ch)])
        if rows[-1] < 12:
            errors.append(f"{ch!r}: descender stops at row {rows[-1]}")
    return errors


def main():
    glyphs = load()
    errors = check(glyphs)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"{len(glyphs)} glyphs, all checks passed")
        return
    print("// Generated by tools/gen_font.py from fonts/yesos-8x16.txt: do not edit.")
    print("// YesOS 8x16 font: printable ASCII and Latin-1 for Spanish (see the source file).")
    print('#include "font.h"')
    print()
    print("const U8 g_font_8x16[256][16] = {")
    for cp in sorted(glyphs):
        name = repr(chr(cp)) if cp > 0x20 else "space"
        print(f"    [0x{cp:02X}] = {{ " + ", ".join(f"0x{v:02X}" for v in glyphs[cp]) + f" }},   // {name}")
    print("};")


if __name__ == "__main__":
    main()
